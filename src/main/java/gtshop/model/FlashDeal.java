package gtshop.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;

@Entity
@Table(name = "flash_deals")
public class FlashDeal {
    @Id
    private String id;
    @Column(name = "reward_id", nullable = false)
    private String rewardId;
    @Column(name = "discount_percent", nullable = false)
    private int discountPercent;
    @Column(name = "starts_at", nullable = false)
    private Instant startsAt;
    @Column(name = "ends_at", nullable = false)
    private Instant endsAt;
    @Column(name = "max_quantity", nullable = false)
    private int maxQuantity;
    @Column(name = "sold_quantity", nullable = false)
    private int soldQuantity;
    @Column(name = "per_user_limit", nullable = false)
    private int perUserLimit = 2;
    @Column(name = "auto_generated", nullable = false)
    private boolean autoGenerated;
    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    public int remaining() {
        return Math.max(0, maxQuantity - soldQuantity);
    }

    public int dealPrice(int price) {
        return Math.max(1, price * (100 - discountPercent) / 100);
    }

    public String getId() { return id; }
    public void setId(String id) { this.id = id; }
    public String getRewardId() { return rewardId; }
    public void setRewardId(String rewardId) { this.rewardId = rewardId; }
    public int getDiscountPercent() { return discountPercent; }
    public void setDiscountPercent(int discountPercent) { this.discountPercent = discountPercent; }
    public Instant getStartsAt() { return startsAt; }
    public void setStartsAt(Instant startsAt) { this.startsAt = startsAt; }
    public Instant getEndsAt() { return endsAt; }
    public void setEndsAt(Instant endsAt) { this.endsAt = endsAt; }
    public int getMaxQuantity() { return maxQuantity; }
    public void setMaxQuantity(int maxQuantity) { this.maxQuantity = maxQuantity; }
    public int getSoldQuantity() { return soldQuantity; }
    public void setSoldQuantity(int soldQuantity) { this.soldQuantity = soldQuantity; }
    public int getPerUserLimit() { return perUserLimit; }
    public void setPerUserLimit(int perUserLimit) { this.perUserLimit = perUserLimit; }
    public boolean isAutoGenerated() { return autoGenerated; }
    public void setAutoGenerated(boolean autoGenerated) { this.autoGenerated = autoGenerated; }
    public Instant getCreatedAt() { return createdAt; }
    public void setCreatedAt(Instant createdAt) { this.createdAt = createdAt; }
}
