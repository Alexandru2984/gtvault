package gtshop.repository;

import gtshop.model.FlashDeal;
import jakarta.persistence.LockModeType;
import java.time.Instant;
import java.util.List;
import java.util.Optional;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Lock;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

@Repository
public interface FlashDealRepository extends JpaRepository<FlashDeal, String> {
    @Query("select d from FlashDeal d where d.startsAt <= :now and d.endsAt > :now order by d.endsAt, d.id")
    List<FlashDeal> findActive(@Param("now") Instant now);

    @Lock(LockModeType.PESSIMISTIC_WRITE)
    @Query("select d from FlashDeal d where d.id = :id")
    Optional<FlashDeal> findByIdForUpdate(@Param("id") String id);

    @Query("select count(d) > 0 from FlashDeal d where d.autoGenerated = false and d.startsAt <= :now and d.endsAt > :now")
    boolean anyManualActive(@Param("now") Instant now);
}
