CREATE TABLE users (
    id character varying(255) NOT NULL,
    activity_points integer NOT NULL,
    avatar character varying(255),
    email character varying(255),
    name character varying(255),
    password character varying(255),
    streak_days integer DEFAULT 0,
    last_daily_claim_date character varying(32),
    last_quiz_date character varying(32),
    referral_code character varying(64),
    referred_by character varying(64),
    total_points_earned integer DEFAULT 0,
    guild_id character varying(32) DEFAULT 'JAVA_KNIGHTS',
    last_fortune_date character varying(16),
    CONSTRAINT users_pkey PRIMARY KEY (id)
);

CREATE TABLE rewards (
    id character varying(255) NOT NULL,
    category character varying(255),
    description character varying(500),
    full_description character varying(2000),
    image character varying(255),
    in_stock boolean NOT NULL,
    is_new boolean,
    name character varying(255),
    price integer NOT NULL,
    stock_count integer NOT NULL,
    CONSTRAINT rewards_pkey PRIMARY KEY (id)
);

CREATE TABLE cart_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name character varying(255),
    price integer NOT NULL,
    quantity integer NOT NULL,
    reward_id character varying(255),
    user_id character varying(255),
    CONSTRAINT cart_items_pkey PRIMARY KEY (id),
    CONSTRAINT fk709eickf3kc0dujx3ub9i7btf FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE purchase_records (
    id character varying(255) NOT NULL,
    points_spent integer NOT NULL,
    purchase_date timestamp(6) with time zone,
    reward_name character varying(255),
    status character varying(255),
    user_id character varying(255),
    voucher_code character varying(255),
    CONSTRAINT purchase_records_pkey PRIMARY KEY (id),
    CONSTRAINT fkg2j34t93r8upvoch5c98y0t3t FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE point_transactions (
    id character varying(64) NOT NULL,
    user_id character varying(255) NOT NULL,
    type character varying(32) NOT NULL,
    amount integer NOT NULL,
    balance_after integer NOT NULL,
    created_at timestamp without time zone NOT NULL,
    description character varying(255),
    CONSTRAINT point_transactions_pkey PRIMARY KEY (id),
    CONSTRAINT point_transactions_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX idx_point_tx_user_date ON point_transactions (user_id, created_at DESC);

CREATE TABLE product_reviews (
    id character varying(255) NOT NULL,
    reward_id character varying(255) NOT NULL,
    user_id character varying(255) NOT NULL,
    user_name character varying(255) NOT NULL,
    user_avatar character varying(255),
    rating integer NOT NULL,
    comment character varying(1000) NOT NULL,
    created_at timestamp with time zone DEFAULT now(),
    CONSTRAINT product_reviews_pkey PRIMARY KEY (id),
    CONSTRAINT product_reviews_rating_check CHECK (rating >= 1 AND rating <= 5),
    CONSTRAINT product_reviews_reward_id_fkey FOREIGN KEY (reward_id) REFERENCES rewards(id) ON DELETE CASCADE,
    CONSTRAINT product_reviews_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE promo_codes (
    id character varying(255) NOT NULL,
    code character varying(64) NOT NULL,
    discount_points integer DEFAULT 0 NOT NULL,
    discount_percent integer DEFAULT 0 NOT NULL,
    min_order_points integer DEFAULT 0 NOT NULL,
    max_uses integer DEFAULT 1000 NOT NULL,
    current_uses integer DEFAULT 0 NOT NULL,
    is_active boolean DEFAULT true NOT NULL,
    expires_at timestamp with time zone,
    CONSTRAINT promo_codes_pkey PRIMARY KEY (id),
    CONSTRAINT promo_codes_code_key UNIQUE (code)
);

CREATE TABLE reward_proposals (
    id character varying(64) NOT NULL,
    user_id character varying(64) NOT NULL,
    author_name character varying(128) NOT NULL,
    title character varying(128) NOT NULL,
    category character varying(64) NOT NULL,
    description character varying(255) NOT NULL,
    votes_count integer DEFAULT 1 NOT NULL,
    status character varying(32) DEFAULT 'PENDING' NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT reward_proposals_pkey PRIMARY KEY (id),
    CONSTRAINT reward_proposals_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE proposal_votes (
    id character varying(64) NOT NULL,
    proposal_id character varying(64) NOT NULL,
    user_id character varying(64) NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT proposal_votes_pkey PRIMARY KEY (id),
    CONSTRAINT uq_proposal_user UNIQUE (proposal_id, user_id),
    CONSTRAINT proposal_votes_proposal_id_fkey FOREIGN KEY (proposal_id) REFERENCES reward_proposals(id) ON DELETE CASCADE,
    CONSTRAINT proposal_votes_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE user_badges (
    id character varying(255) NOT NULL,
    user_id character varying(255) NOT NULL,
    badge_code character varying(64) NOT NULL,
    badge_title character varying(128) NOT NULL,
    badge_description character varying(255),
    badge_icon character varying(32) NOT NULL,
    unlocked_at timestamp with time zone DEFAULT now(),
    CONSTRAINT user_badges_pkey PRIMARY KEY (id),
    CONSTRAINT uq_user_badge UNIQUE (user_id, badge_code),
    CONSTRAINT user_badges_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE user_quests (
    id character varying(64) NOT NULL,
    user_id character varying(64) NOT NULL,
    quest_key character varying(64) NOT NULL,
    quest_type character varying(16) NOT NULL,
    title character varying(128) NOT NULL,
    description character varying(255) NOT NULL,
    reward_points integer NOT NULL,
    current_progress integer DEFAULT 0 NOT NULL,
    target_progress integer DEFAULT 1 NOT NULL,
    completed boolean DEFAULT false NOT NULL,
    claimed boolean DEFAULT false NOT NULL,
    quest_date character varying(16) NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT user_quests_pkey PRIMARY KEY (id),
    CONSTRAINT user_quests_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX idx_user_quests_user_date ON user_quests (user_id, quest_date);
