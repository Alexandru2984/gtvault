-- ---------------------------------------------------------------- limite zilnice per utilizator
CREATE TABLE user_daily_counters (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id character varying(255) NOT NULL,
    counter_date character varying(16) NOT NULL,
    counter_key character varying(32) NOT NULL,
    counter_value integer DEFAULT 0 NOT NULL,
    CONSTRAINT user_daily_counters_pkey PRIMARY KEY (id),
    CONSTRAINT ux_user_daily_counter UNIQUE (user_id, counter_date, counter_key),
    CONSTRAINT fk_daily_counter_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

