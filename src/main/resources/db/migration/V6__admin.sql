-- ---------------------------------------------------------------- jurnal de audit
-- Fara cheie straina catre users: jurnalul trebuie sa ramana si daca un cont este sters.
CREATE TABLE admin_audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    admin_id character varying(255) NOT NULL,
    action character varying(48) NOT NULL,
    target_type character varying(32) NOT NULL,
    target_id character varying(255),
    details character varying(1000),
    ip character varying(64),
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT admin_audit_log_pkey PRIMARY KEY (id)
);
CREATE INDEX idx_audit_date ON admin_audit_log (created_at DESC);
CREATE INDEX idx_audit_target ON admin_audit_log (target_type, target_id);

